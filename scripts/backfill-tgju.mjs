// Generates worker/migrations/0006_backfill_daily.sql (#186): a daily price for
// every tracked symbol and every day since the dataset began that the public
// dataset (a copy of production before 2026-10-03) has none for, taken from
// tgju's own daily history. Run: node scripts/backfill-tgju.mjs
import { writeFileSync, readFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { backfillStatements, missingDays, tehranDay } from "./tgju-history.mjs";

const TRACKED = JSON.parse(readFileSync(new URL("../worker/src/symbols.json", import.meta.url), "utf8"));
const USD_PRICED = ["ons", "silver", "oil_brent", "crypto-ethereum"];
const HISTORY = (key) =>
  `https://api.tgju.org/v1/market/indicator/summary-table-data/${encodeURIComponent(key)}?lang=en&order_dir=desc&start=0&length=5000&convert_to_ad=1`;
const OUT = new URL("../worker/migrations/0006_backfill_daily.sql", import.meta.url);

async function json(url) {
  const response = await fetch(url, { headers: { "user-agent": "Mozilla/5.0 (pricedb backfill)" } });
  if (!response.ok) throw new Error(`${url} responded ${response.status}`);
  return response.json();
}

// Days each symbol already has, from the latest public dataset
async function knownDays() {
  const releases = await json("https://api.github.com/repos/margani/pricedb/releases?per_page=20");
  const release = releases.find((r) => r.tag_name.startsWith("dataset-"));
  const asset = release.assets.find((a) => a.name === "prices-daily.csv.gz");
  const csv = gunzipSync(Buffer.from(await (await fetch(asset.browser_download_url)).arrayBuffer())).toString("utf8");
  const days = new Map();
  for (const line of csv.trim().split("\n").slice(1)) {
    const [symbol, time] = line.split(",");
    if (!days.has(symbol)) days.set(symbol, new Set());
    days.get(symbol).add(tehranDay(time));
  }
  return { release: release.tag_name, days };
}

const { release, days } = await knownDays();
const from = [...days.values()].flatMap((s) => [...s]).sort()[0];
// Up to yesterday in Tehran; today's daily record comes from the cron
const to = tehranDay(new Date(Date.now() - 24 * 60 * 60 * 1000).toISOString());

const lines = [];
let total = 0;
const summary = [];
for (const key of TRACKED) {
  try {
    const history = await json(HISTORY(key));
    const rows = missingDays(history.data ?? [], days.get(key) ?? new Set(), from, to);
    lines.push(...backfillStatements(key, rows));
    total += rows.length;
    summary.push(`${key}: ${rows.length}`);
  } catch (error) {
    summary.push(`${key}: FAILED ${error.message}`);
  }
  await new Promise((resolve) => setTimeout(resolve, 500)); // be gentle with tgju
}

const derived = `
-- Rial copies of the backfilled USD-priced days, as in 0005_rial_prices.sql
INSERT OR IGNORE INTO prices (symbol, granularity, ts, price, high, low, raw)
SELECT 'irr:' || p.symbol, p.granularity, p.ts, ROUND(p.price * u.price), ROUND(p.high * u.price), ROUND(p.low * u.price), ''
FROM prices p
JOIN prices u
  ON u.symbol = 'price_dollar_rl'
 AND u.granularity = p.granularity
 AND u.ts = (
   SELECT MAX(ts) FROM prices
   WHERE symbol = 'price_dollar_rl' AND granularity = p.granularity AND ts <= p.ts
 )
WHERE p.granularity = 'daily' AND p.symbol IN (${USD_PRICED.map((s) => `'${s}'`).join(", ")});
`;

writeFileSync(
  OUT,
  `-- Daily prices backfilled from tgju's history (#186), generated by
-- scripts/backfill-tgju.mjs on ${new Date().toISOString().slice(0, 10)} against ${release}, for ${from}..${to}.
-- Each row is inserted only if its symbol has no daily record that Tehran day.
${lines.join("\n")}
${derived}`
);
console.log(summary.join("\n"));
console.log(`${total} rows in ${lines.length} statements for ${from}..${to}`);
